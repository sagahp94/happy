/**
 * Hàm chuẩn hóa chuỗi tiếng Việt chuẩn NFC theo yêu cầu.
 */
export const chuanHoaTiengViet = (vanBan: string): string => {
  if (!vanBan) return "";
  return vanBan.normalize("NFC");
};

/**
 * Kiểm tra tính hợp lệ và toàn vẹn của chuỗi tiếng Việt.
 * Đảm bảo ký tự đầu tiên và cuối cùng không bị mất, không bị rỗng.
 */
export const kiemTraToanVenVanBan = (
  goc: string,
  hienThi: string
): { hopLe: boolean; lyDo?: string } => {
  const gocNFC = chuanHoaTiengViet(goc);
  const hienThiNFC = chuanHoaTiengViet(hienThi);

  if (gocNFC !== hienThiNFC) {
    return {
      hopLe: false,
      lyDo: `Chuỗi không khớp. Gốc: "${gocNFC}", Hiển thị: "${hienThiNFC}"`,
    };
  }

  if (gocNFC.length > 0 && hienThiNFC[0] !== gocNFC[0]) {
    return {
      hopLe: false,
      lyDo: `Ký tự đầu tiên không khớp. Gốc: '${gocNFC[0]}', Hiển thị: '${hienThiNFC[0]}'`,
    };
  }

  return { hopLe: true };
};
